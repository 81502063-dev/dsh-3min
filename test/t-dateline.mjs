const s = '新华社深圳11月19日电(记者温馨、李思佳)11月19日上午，国家主席习近平夫人彭丽媛同配偶在深圳湾文化广场举行集体活动。'

const patterns = [
  /^(?:新华社|中新社|中新网|人民网|央视新闻|光明日报|经济日报|中国青年报|科技日报)[^。]{0,30}电[（(]记者[^）)]{0,30}[）)]?\s*/,
  /^[\u4e00-\u9fa5]{2,8}(?:社|报|台|网)\s*[^\s，。]{0,10}\d{1,2}月\d{1,2}日(?:电|讯)\s*[（(][^）)]{0,30}[）)]?\s*/,
  /^[^\s，。]{0,16}[（(]记者[^）)]{0,30}[）)]\s*/,
]

for (const re of patterns) {
  const out = s.replace(re, '')
  console.log(String(re).slice(0, 40), '=>', out.slice(0, 30), '| changed:', out !== s)
}
